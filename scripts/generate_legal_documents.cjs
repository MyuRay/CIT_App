'use strict';
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const data = JSON.parse(fs.readFileSync(path.join(root, 'legal/documents.json'), 'utf8'));
const draft = data.publication?.status !== 'published';
if (!draft && !/^\d{4}-\d{2}-\d{2}$/.test(data.publication?.effectiveDate || '')) {
  throw Error('Published legal documents require an effective date.');
}
const dartString = value => JSON.stringify(value).replace(/\$/g, '\\$');
const effectiveDate = data.publication?.effectiveDate
  ? data.publication.effectiveDate.replace(/^(\d{4})-(\d{2})-(\d{2})$/, (_, year, month, day) => `${year}年${Number(month)}月${Number(day)}日`)
  : '';
const dart = [
  '// Generated by scripts/generate_legal_documents.cjs. Edit legal/documents.json.',
  "import 'legal_document.dart';", '',
  `const legalDocumentVersion = ${dartString(data.version)};`,
  `const legalDocumentUpdated = ${dartString(data.updated)};`, '',
  `const legalDocumentIsDraft = ${draft};`, '',
  `const legalDocumentEffectiveDate = ${dartString(effectiveDate)};`, '',
];
const outputs = new Map();
for (const [key, filename] of [['terms', 'TERMS_OF_SERVICE.md'], ['privacy', 'PRIVACY_POLICY.md']]) {
  const document = data[key];
  dart.push(`const ${key}Document = LegalDocument(`, `  title: ${dartString(document.title)},`, '  sections: [');
  for (const section of document.sections) {
    dart.push('    LegalSection(', `      title: ${dartString(section.title)},`,
      `      body: ${dartString(section.body)},`,
      ...(section.anchor ? [`      anchor: ${dartString(section.anchor)},`] : []), '    ),');
  }
  dart.push('  ],', ');', '');
  const status = draft ? '公開前の改訂案。施行日は未確定です。' : `施行日：${effectiveDate}`;
  outputs.set(filename, `<!-- Generated from legal/documents.json; do not edit directly. -->\n# ${document.title}\n\n${status}\n\n最終更新日：${data.updated}\n\n文書バージョン：${data.version}\n\n` +
    document.sections.map(section => `## ${section.title}\n\n${section.body.replace(/\n+/g, '\n\n')}\n`).join('\n'));
}
outputs.set('lib/core/legal/legal_documents.g.dart', dart.join('\n'));
for (const [filename, content] of outputs) {
  const file = path.join(root, filename);
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n') !== content) {
      throw Error(`Generated legal document is out of date: ${filename}`);
    }
  } else {
    fs.mkdirSync(path.dirname(file), {recursive: true});
    fs.writeFileSync(file, content, 'utf8');
  }
}
console.log(process.argv.includes('--check') ? 'Legal documents are in sync.' : 'Legal documents generated.');
